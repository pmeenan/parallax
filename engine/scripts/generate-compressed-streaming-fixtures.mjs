import { MeshoptEncoder } from "meshoptimizer/encoder";
import { loadPinnedKtxEncoder } from "./ktx-encoder-pin.mjs";
import { preencodeUastcAsBc7 } from "./preencode-bc7.mjs";

const ktx = await loadPinnedKtxEncoder();
await MeshoptEncoder.ready;

const fixtures = [makeFixture("compact", 32, 16, 4, 3), makeFixture("expanded", 128, 64, 32, 16)];
const mipChain = makeMipChainFixture(16, 8);
const rawChains = [false, true].map((zstd) => makeRawRgba8Fixture(8, 4, zstd));
const bc1Chain = makeBc1Fixture(8, 8);
const bc7Chain = await makePreencodedBc7Fixture(mipChain);
const source =
  `// Generated by engine/scripts/generate-compressed-streaming-fixtures.mjs.\n` +
  `// Web-libktx 4.4.2 uses UASTC, one thread, SSE disabled, and no RDO.\n` +
  `export const PRODUCTION_COMPRESSED_STREAMING_FIXTURES = Object.freeze(${JSON.stringify(fixtures, null, 2)} as const);\n` +
  `// A complete authored UASTC mip chain (level DEFAULT), for the schema-v2 and BC7 paths.\n` +
  `export const UASTC_MIP_CHAIN_FIXTURE = Object.freeze(${JSON.stringify(mipChain, null, 2)} as const);\n` +
  `// Raw linear RGBA8 mip chains, plain and zstd-supercompressed, for lossless maps.\n` +
  `export const RAW_RGBA8_MIP_CHAIN_FIXTURES = Object.freeze(${JSON.stringify(rawChains, null, 2)} as const);\n` +
  `// A pre-encoded sRGB BC1 mip chain (UASTC transcoded at pack time), with its stored blocks.\n` +
  `export const BC1_MIP_CHAIN_FIXTURE = Object.freeze(${JSON.stringify(bc1Chain, null, 2)} as const);\n` +
  `// UASTC_MIP_CHAIN_FIXTURE pre-transcoded to BC7 at pack time, with its stored blocks.\n` +
  `export const BC7_MIP_CHAIN_FIXTURE = Object.freeze(${JSON.stringify(bc7Chain, null, 2)} as const);\n`;
process.stdout.write(source);

function mipLevels(width, height) {
  const levels = [];
  for (let w = width, h = height; ; w = Math.max(1, w >> 1), h = Math.max(1, h >> 1)) {
    const rgba = new Uint8Array(w * h * 4);
    for (let y = 0; y < h; y += 1)
      for (let x = 0; x < w; x += 1)
        rgba.set(
          [(x * 37 + levels.length * 50) & 255, (y * 61) & 255, ((x + y) * 23) & 255, 255],
          (y * w + x) * 4,
        );
    levels.push(rgba);
    if (w === 1 && h === 1) return levels;
  }
}

function makeRawRgba8Fixture(width, height, zstd) {
  const levels = mipLevels(width, height);
  const info = new ktx.textureCreateInfo();
  info.vkFormat = ktx.VkFormat.R8G8B8A8_UNORM;
  info.baseWidth = width;
  info.baseHeight = height;
  info.baseDepth = 1;
  info.numDimensions = 2;
  info.numLevels = levels.length;
  info.numLayers = 1;
  info.numFaces = 1;
  info.isArray = false;
  info.generateMipmaps = false;
  const texture = new ktx.texture(info, ktx.TextureCreateStorageEnum.ALLOC_STORAGE);
  for (const [level, rgba] of levels.entries()) texture.setImageFromMemory(level, 0, 0, rgba);
  if (zstd && texture.deflateZstd(9) !== ktx.ErrorCode.SUCCESS) throw new Error("zstd failed");
  const ktx2 = Uint8Array.from(texture.writeToMemory());
  texture.delete();
  info.delete();
  return {
    height,
    ktx2: Buffer.from(ktx2).toString("base64"),
    mipLevelCount: levels.length,
    rgba: Buffer.concat(levels).toString("base64"),
    width,
    zstd,
  };
}

async function makePreencodedBc7Fixture(uastc) {
  const { ktx2, levels } = await preencodeUastcAsBc7(ktx, Buffer.from(uastc.ktx2, "base64"), false);
  return {
    blocks: Buffer.concat(levels).toString("base64"),
    height: uastc.height,
    ktx2: Buffer.from(ktx2).toString("base64"),
    mipLevelCount: uastc.mipLevelCount,
    width: uastc.width,
  };
}

function makeBc1Fixture(width, height) {
  const levels = mipLevels(width, height);
  const info = new ktx.textureCreateInfo();
  info.vkFormat = ktx.VkFormat.R8G8B8A8_SRGB;
  info.baseWidth = width;
  info.baseHeight = height;
  info.baseDepth = 1;
  info.numDimensions = 2;
  info.numLevels = levels.length;
  info.numLayers = 1;
  info.numFaces = 1;
  info.isArray = false;
  info.generateMipmaps = false;
  const texture = new ktx.texture(info, ktx.TextureCreateStorageEnum.ALLOC_STORAGE);
  for (const [level, rgba] of levels.entries()) texture.setImageFromMemory(level, 0, 0, rgba);
  const basis = new ktx.basisParams();
  basis.uastc = true;
  basis.threadCount = 1;
  basis.noSSE = true;
  basis.uastcRDO = false;
  basis.uastcRDONoMultithreading = true;
  basis.uastcFlags = ktx.pack_uastc_flag_bits.LEVEL_DEFAULT;
  if (texture.compressBasis(basis) !== ktx.ErrorCode.SUCCESS)
    throw new Error("UASTC encode failed");
  if (texture.transcodeBasis(ktx.TranscodeTarget.BC1_RGB, 0) !== ktx.ErrorCode.SUCCESS)
    throw new Error("BC1 transcode failed");
  const blocks = levels.map((_, level) => Buffer.from(texture.getImage(level, 0, 0)));
  const ktx2 = Uint8Array.from(texture.writeToMemory());
  texture.delete();
  basis.delete();
  info.delete();
  return {
    blocks: Buffer.concat(blocks).toString("base64"),
    height,
    ktx2: Buffer.from(ktx2).toString("base64"),
    mipLevelCount: levels.length,
    width,
  };
}

