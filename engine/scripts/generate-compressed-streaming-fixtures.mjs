import { MeshoptEncoder } from "meshoptimizer/encoder";
import { loadPinnedKtxEncoder } from "./ktx-encoder-pin.mjs";

const ktx = await loadPinnedKtxEncoder();
await MeshoptEncoder.ready;

const fixtures = [makeFixture("compact", 32, 16, 4, 3), makeFixture("expanded", 128, 64, 32, 16)];
const source =
  `// Generated by engine/scripts/generate-compressed-streaming-fixtures.mjs.\n` +
  `// Web-libktx 4.4.2 uses UASTC, one thread, SSE disabled, and no RDO.\n` +
  `export const PRODUCTION_COMPRESSED_STREAMING_FIXTURES = Object.freeze(${JSON.stringify(fixtures, null, 2)} as const);\n`;
process.stdout.write(source);

function makeFixture(id, width, height, columns, rows) {
  const rgba = new Uint8Array(width * height * 4);
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const offset = (y * width + x) * 4;
      rgba[offset] = (x * 17 + y * 3 + columns) & 255;
      rgba[offset + 1] = (x * 5 + y * 29 + rows) & 255;
      rgba[offset + 2] = ((x ^ y) * 11 + width) & 255;
      rgba[offset + 3] = 255;
    }
  }
  const info = new ktx.textureCreateInfo();
  info.vkFormat = ktx.VkFormat.R8G8B8A8_SRGB;
  info.baseWidth = width;
  info.baseHeight = height;
  info.baseDepth = 1;
  info.numDimensions = 2;
  info.numLevels = 1;
  info.numLayers = 1;
  info.numFaces = 1;
  info.isArray = false;
  info.generateMipmaps = false;
  const texture = new ktx.texture(info, ktx.TextureCreateStorageEnum.ALLOC_STORAGE);
  texture.setImageFromMemory(0, 0, 0, rgba);
  const basis = new ktx.basisParams();
  basis.uastc = true;
  basis.threadCount = 1;
  basis.noSSE = true;
  basis.uastcRDO = false;
  basis.uastcRDONoMultithreading = true;
  texture.compressBasis(basis);
  const ktx2 = Uint8Array.from(texture.writeToMemory());
  texture.delete();
  basis.delete();
  info.delete();

  const vertexCount = (columns + 1) * (rows + 1);
  const attributes = new Float32Array(vertexCount * 8);
  for (let row = 0; row <= rows; row += 1) {
    for (let column = 0; column <= columns; column += 1) {
      const vertex = row * (columns + 1) + column;
      attributes.set(
        [
          column,
          Math.sin(column * 0.2) * Math.cos(row * 0.3),
          row,
          0,
          1,
          0,
          column / columns,
          row / rows,
        ],
        vertex * 8,
      );
    }
  }
  const indices = new Uint32Array(columns * rows * 6);
  let cursor = 0;
  for (let row = 0; row < rows; row += 1) {
    for (let column = 0; column < columns; column += 1) {
      const a = row * (columns + 1) + column;
      const b = a + 1;
      const c = a + columns + 1;
      const d = c + 1;
      indices.set([a, c, b, b, c, d], cursor);
      cursor += 6;
    }
  }
  const attributeBytes = new Uint8Array(attributes.buffer);
  const indexBytes = new Uint8Array(indices.buffer);
  return {
    attributes: Buffer.from(
      MeshoptEncoder.encodeGltfBuffer(attributeBytes, vertexCount, 32, "ATTRIBUTES", 0),
    ).toString("base64"),
    height,
    id,
    indexCount: indices.length,
    indices: Buffer.from(
      MeshoptEncoder.encodeGltfBuffer(indexBytes, indices.length, 4, "TRIANGLES", 0),
    ).toString("base64"),
    ktx2: Buffer.from(ktx2).toString("base64"),
    vertexCount,
    width,
  };
}
